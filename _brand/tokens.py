def _vars(d, indent='  '):
    return '\n'.join('%s--%s: %s;' % (indent, k, v) for k, v in d.items())


def css():
    """The token block, emitted into every page by the builders.

    Theme handling is deliberate: the palette is defined on bare :root, redefined
    under prefers-color-scheme for the OS default, and redefined AGAIN under
    [data-theme] so an explicit toggle beats the media query in both directions.
    A colour defined only inside a media query is how a page ends up unreadable
    for the half of visitors on the other setting.
    """
    return (
        "/* Generated by _brand/tokens.py -- do not edit in the page.\n"
        "   One palette, one scale. A page that declares its own colours has\n"
        "   opted out of the design system and will drift. */\n"
        ":root {\n" + _vars(LIGHT) + "\n" + SCALE + "}\n"
        "@media (prefers-color-scheme: dark) {\n"
        "  :root:not([data-theme=\"light\"]) {\n" + _vars(DARK, '    ') + "\n  }\n}\n"
        ":root[data-theme=\"dark\"] {\n" + _vars(DARK) + "\n}\n"
        ":root[data-theme=\"light\"] {\n" + _vars(LIGHT) + "\n}\n"
    )


def contrast(hex_a, hex_b):
    """WCAG contrast ratio, so the palette can be CHECKED rather than admired. A
    brass that looks lovely and fails AA on body text is a bug, not a taste."""
    def lum(h):
        h = h.lstrip('#')
        parts = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
        parts = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in parts]
        return 0.2126 * parts[0] + 0.7152 * parts[1] + 0.0722 * parts[2]
    a, b = lum(hex_a), lum(hex_b)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)



"""One palette, one type scale, one spacing rhythm -- for every page.

WHY THIS EXISTS. Measured 2026-08-11: every page on this site declared its own
CSS custom properties and NONE shared a source. The homepage used --ink #1F1C15
while its own tools used #211D14 -- close enough that nobody consciously notices,
far enough that the pages feel subtly unrelated. skeleton was blueprint navy and
almanac warm brass. Three different companies, one domain.

That is the same defect as the duplicated parser and the three-copy test harness,
in the design layer: no single source, so agreement is luck and drift is
guaranteed. The fix is the same shape. After this, a new tool CANNOT be off-brand,
because it does not declare its own colours.

THE DIRECTION, and why each choice rather than the obvious one:

  GROUND -- warm off-black and warm parchment, never neutral grey. Almost every
  developer-tool site is cool grey or pure black; warm reads as chosen. A pure
  mid-grey reads as unconsidered, so every neutral here carries a slight hue bias
  toward the accent.

  ACCENT -- a single brass. It appears on interactive things and on the one number
  you are meant to look at, and nowhere else. Restraint is what makes an accent
  read as expensive; using it everywhere is what makes a page look like a demo.

  SEMANTIC -- good/warn/bad are SEPARATE from the accent and never borrow it. A
  page where "success" and "this link" are the same colour cannot show a clean
  result and a call to action at the same time.

  TYPE -- one scale. Tracking tightens as size grows, which keeps large text from
  looking loose and small text from looking cramped; tabular figures wherever
  digits line up in a column.

  NOT USED, deliberately: gradients, glassmorphism, purple-to-blue heroes. Those
  read as machine-generated in 2026 and would undercut the only thing this site
  actually sells, which is that the work is careful.
"""

